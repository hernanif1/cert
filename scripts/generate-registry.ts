/**
 * Regenerates the two content registries from the files on disk.
 *
 * Static export needs static imports, so the registries cannot be built with a
 * dynamic glob at runtime. Writing them by hand across 38 lesson files and 38
 * question files is a reliable source of "authored but never wired up" bugs, so
 * they are generated instead — run `npm run registry` after adding content.
 *
 * Content files themselves are never touched.
 */
import { readdirSync, existsSync, writeFileSync, readFileSync } from "node:fs";
import { join } from "node:path";

const ROOT = join(import.meta.dirname, "..");
const LESSON_DIR = join(ROOT, "content/lessons");
const QUESTION_DIR = join(ROOT, "content/questions");

const SKIP_LESSONS = new Set(["index.ts", "registry.ts"]);

function identifier(prefix: string, name: string): string {
  return prefix + name.replace(/[^a-zA-Z0-9]/g, "_");
}

/* ── Lessons ─────────────────────────────────────────────────────────── */

const lessonFiles = readdirSync(LESSON_DIR)
  .filter((f) => f.endsWith(".ts") && !SKIP_LESSONS.has(f))
  .sort();

const lessonImports: string[] = [];
const lessonEntries: string[] = [];

for (const file of lessonFiles) {
  const slug = file.replace(/\.ts$/, "");
  const source = readFileSync(join(LESSON_DIR, file), "utf8");
  if (!/export const lesson\b/.test(source)) {
    console.error(`  skip  ${file} — no 'export const lesson'`);
    continue;
  }
  const id = identifier("l_", slug);
  lessonImports.push(
    `import { lesson as ${id} } from "@/content/lessons/${slug}";`,
  );
  lessonEntries.push(`  [${id}.slug]: ${id},`);
}

writeFileSync(
  join(LESSON_DIR, "registry.ts"),
  `// GENERATED by scripts/generate-registry.ts — do not edit by hand.
// Run \`npm run registry\` after adding or removing a lesson file.
import type { Lesson } from "@/content/schema";

${lessonImports.join("\n")}

/**
 * Authored lesson bodies, keyed by slug.
 *
 * This module carries no \`server-only\` marker so build tooling — the content
 * validator in particular — can import it in a plain Node context. Application
 * code goes through ./index.ts, which adds that marker and is what stops a
 * client component pulling all 38 lesson bodies into its bundle.
 */
export const AUTHORED: Record<string, Lesson> = {
${lessonEntries.join("\n")}
};
`,
);

/* ── Questions ───────────────────────────────────────────────────────── */

const questionImports: string[] = [];
const questionSpreads: string[] = [];

for (const dir of readdirSync(QUESTION_DIR).filter((d) => /^d[1-7]$/.test(d)).sort()) {
  const full = join(QUESTION_DIR, dir);
  if (!existsSync(full)) continue;
  for (const file of readdirSync(full).filter((f) => f.endsWith(".ts")).sort()) {
    const base = file.replace(/\.ts$/, "");
    const id = identifier("q_", `${dir}_${base}`);
    questionImports.push(
      `import { questions as ${id} } from "@/content/questions/${dir}/${base}";`,
    );
    questionSpreads.push(`  ...${id},`);
  }
}

// Mock Form A lives in its own directory so it can be authored in parallel
// without two writers contending for one file.
const reservedDir = join(QUESTION_DIR, "reserved");
if (existsSync(reservedDir)) {
  for (const file of readdirSync(reservedDir).filter((f) => f.endsWith(".ts")).sort()) {
    const base = file.replace(/\.ts$/, "");
    const id = identifier("r_", base);
    questionImports.push(
      `import { questions as ${id} } from "@/content/questions/reserved/${base}";`,
    );
    questionSpreads.push(`  ...${id},`);
  }
}

writeFileSync(
  join(QUESTION_DIR, "index.ts"),
  `// GENERATED by scripts/generate-registry.ts — do not edit by hand.
// Run \`npm run registry\` after adding or removing a question file.
import type {
  DomainNumber,
  ObjectiveId,
  Question,
  QuestionId,
} from "@/content/schema";

${questionImports.join("\n")}

/**
 * The question bank: one central pool, referenced by id.
 *
 * Questions deliberately do NOT live inside lesson files. A lesson's Practice
 * Scenario is a render of \`practiceQuestionIds[0]\`, so an item has exactly one
 * identity and exactly one drill card. Colocating would give the same question
 * two identities and make its review history ambiguous.
 *
 * \`pool: "drill"\` is the 200-item practice pool; \`pool: "reserved"\` is the
 * 63-item Mock Form A, which drill never touches until a first mock is taken.
 *
 * Question ids are IMMUTABLE once shipped — drill state is keyed by them. A bad
 * question gets \`retired: true\`, never deletion or renumbering.
 */
export const QUESTIONS: Question[] = [
${questionSpreads.join("\n")}
];

const BY_ID = new Map<string, Question>(QUESTIONS.map((q) => [q.id, q]));

export function getQuestion(id: QuestionId): Question | undefined {
  return BY_ID.get(id);
}

export function questionsByObjective(objective: ObjectiveId): Question[] {
  return QUESTIONS.filter((q) => q.objective === objective && !q.retired);
}

export function drillPool(): Question[] {
  return QUESTIONS.filter((q) => q.pool === "drill" && !q.retired);
}

export function drillPoolByDomain(domain: DomainNumber): Question[] {
  return drillPool().filter((q) => q.domain === domain);
}

export function reservedForm(): Question[] {
  return QUESTIONS.filter((q) => q.pool === "reserved" && !q.retired);
}

/** Objective ids that have at least one live question. */
export const OBJECTIVES_WITH_QUESTIONS: Set<string> = new Set(
  QUESTIONS.filter((q) => !q.retired).map((q) => q.objective),
);
`,
);

console.log(
  `registry: ${lessonEntries.length} lesson(s), ${questionSpreads.length} question file(s)`,
);
